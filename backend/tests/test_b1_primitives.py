@pytest.mark.asyncio
async def test_remote_parser():
    class Runner:
        async def run(self, args):
            from app.repos_git.git_runner import GitResult

            return GitResult(b"ref: refs/heads/main\tHEAD\nabc123\tHEAD\n", b"", 0)

    info = await get_remote_info(Runner(), "unused")
    assert info.default_branch == "main" and info.head_sha == "abc123"
